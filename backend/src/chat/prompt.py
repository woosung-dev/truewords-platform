def compose_system_prompt(
    base: str,
    mode: str | None,
    persona: str | None,
) -> str:
    """공통 base + 모드별 모듈 + persona {persona} placeholder 치환.

    mode 가 None/unknown 이면 'standard' 폴백.
    """
